"""
Generate the MicroPython constants module for the firmware.

Output is plain `NAME = literal` lines: no imports, no typing, no containers. Anything
more would cost RAM on the Pico, and the firmware only needs the wire strings.
"""

import json
from collections.abc import Iterator
from importlib.metadata import version
from typing import Any, get_args

from pydantic import BaseModel

from datenspec.models import (
    LAPTOP_MODELS,
    RECORD_MODELS,
    SCHEMA_VERSION,
    LedDuty,
    RecordHeader,
    TcsRaw,
)
from datenspec.models.vocab import (
    AckResult,
    AlarmId,
    AlarmSeverity,
    AlertState,
    CmdAction,
    GainMode,
    Illumination,
    LaptopKind,
    LedId,
    LogLevel,
    ModuleState,
    RecordKind,
    RunEndReason,
    RunEvent,
    StatusPayload,
    TcsChannel,
)
from datenspec.topics import TOPICS

OUTPUT = "pico/datenspec_const.py"

# Prefix keeps values unambiguous where the same string means different things,
# e.g. "nir" is an LED (LED_NIR), a channel (CH_NIR) and an illumination (ILL_NIR).
VALUE_SETS: tuple[tuple[str, str, Any], ...] = (
    ("K_", "record kinds (k)", RecordKind),
    ("K_", "laptop message kinds (k); cmd is received by the device", LaptopKind),
    ("ILL_", "illumination (ill)", Illumination),
    ("GAIN_", "gain control mode (cfg.capture.gain_control.mode)", GainMode),
    ("LED_", "LED IDs; also the keys of led", LedId),
    ("CH_", "TCS3448 channels; also the keys of raw", TcsChannel),
    ("ALARM_", "alarm IDs (id)", AlarmId),
    ("SEV_", "alarm severity (sev)", AlarmSeverity),
    ("ALERT_", "alert state (state)", AlertState),
    ("STATE_", "module state (mqtt.state, sd.state, err.state)", ModuleState),
    ("STATUS_", "status topic payload (plain text)", StatusPayload),
    ("LVL_", "log level (lvl)", LogLevel),
    ("EV_", "run event (ev)", RunEvent),
    ("END_", "run end reason (reason)", RunEndReason),
    ("ACT_", "command action (act)", CmdAction),
    ("RES_", "ack result (res)", AckResult),
)

# Their keys are exactly LED IDs / channel names, already emitted as LED_* / CH_*.
KEYED_BY_VALUE_SET: dict[type[BaseModel], Any] = {LedDuty: LedId, TcsRaw: TcsChannel}

UNIT_COMMENT = {"1": "dimensionless"}


def _wire_name(model: type[BaseModel], attr: str) -> str:
    return model.model_fields[attr].alias or attr


def _nested_models(annotation: Any) -> Iterator[type[BaseModel]]:
    if isinstance(annotation, type) and issubclass(annotation, BaseModel):
        yield annotation
    for arg in get_args(annotation):
        yield from _nested_models(arg)


def _walk(roots: tuple[type[BaseModel], ...]) -> list[type[BaseModel]]:
    """All models reachable from roots, depth-first, each once."""
    seen: list[type[BaseModel]] = []

    def visit(model: type[BaseModel]) -> None:
        if model in seen:
            return
        seen.append(model)
        for field in model.model_fields.values():
            for nested in _nested_models(field.annotation):
                visit(nested)

    for root in roots:
        visit(root)
    return seen


def _units_by_name(models: list[type[BaseModel]]) -> dict[str, list[str]]:
    # Same wire name may occur in several models; list every unit so none is hidden.
    units: dict[str, list[str]] = {}
    for model in models:
        for attr, field in model.model_fields.items():
            extra = field.json_schema_extra
            unit = extra.get("x-unit") if isinstance(extra, dict) else None
            bucket = units.setdefault(_wire_name(model, attr), [])
            if unit is not None and unit not in bucket:
                bucket.append(unit)
    return units


def _check_keyed_models() -> None:
    for model, value_set in KEYED_BY_VALUE_SET.items():
        keys = {_wire_name(model, attr) for attr in model.model_fields}
        values = set(get_args(value_set))
        if keys != values:
            raise ValueError(f"{model.__name__} keys {sorted(keys)} != {sorted(values)}")


def _const(name: str, value: object, comment: str | None = None) -> str:
    if not name.isidentifier():
        raise ValueError(f"not an identifier: {name!r}")
    # json.dumps gives double-quoted strings, matching ruff format; valid Python for ASCII.
    literal = json.dumps(value) if isinstance(value, str) else repr(value)
    line = f"{name} = {literal}"
    return f"{line}  # {comment}" if comment else line


def render() -> str:
    _check_keyed_models()
    models = _walk((RecordHeader, *RECORD_MODELS, *LAPTOP_MODELS))
    units = _units_by_name(models)

    out = [
        "# Generated by datenspec.codegen.pico - do not edit.",
        f"# datenspec {version('datenspec')}, schema version {SCHEMA_VERSION}",
        "",
        _const("SCHEMA_VERSION", SCHEMA_VERSION),
        "",
        "# Topics: fill with .format(device_id=..., alarm_id=...).",
    ]
    # Laptop-to-pipeline topics would only cost RAM on the device.
    for topic in (t for t in TOPICS if "pico" in {t.sender, t.receiver}):
        suffix = topic.name.upper()
        out.append(_const(f"T_{suffix}", topic.template))
        out.append(_const(f"QOS_{suffix}", topic.qos))
        out.append(_const(f"RETAIN_{suffix}", topic.retain))

    for prefix, title, value_set in VALUE_SETS:
        out += ["", f"# {title}"]
        out += [_const(prefix + v.upper(), v) for v in get_args(value_set)]

    out += ["", "# Field names on the wire; unit in the comment."]
    emitted: set[str] = set()
    for model in models:
        if model in KEYED_BY_VALUE_SET:
            continue
        fresh = [
            _wire_name(model, attr)
            for attr in model.model_fields
            if _wire_name(model, attr) not in emitted
        ]
        if not fresh:
            continue
        out.append(f"# {model.__name__}")
        for name in fresh:
            emitted.add(name)
            unit = " | ".join(UNIT_COMMENT.get(u, u) for u in units[name]) or None
            out.append(_const(f"F_{name.upper()}", name, unit))

    return "\n".join(out) + "\n"
