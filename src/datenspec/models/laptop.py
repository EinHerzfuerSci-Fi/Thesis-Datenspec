"""
Messages sent by the laptop (CLI), not by the Pico. They carry only v and k: no dev,
boot or up, because the laptop is not a measurement device. The target of a cmd is in
its topic, not in the payload.
"""

from typing import Annotated, Any, Literal, Self

from pydantic import ConfigDict, Field, TypeAdapter, model_validator

from ._base import FORBID_EXTRA, Count, HexId16, Uuid, meta
from .header import MessageHeader
from .profile import ProfileName
from .vocab import SessionVariety

LaptopTimestamp = Annotated[float, Field(ge=0.0)]
TagKey = Annotated[str, Field(pattern=r"^[a-z0-9_]+$")]


class _Cmd(MessageHeader):
    kind: Literal["cmd"] = Field(alias="k", json_schema_extra=meta(since=2))
    id: Uuid = Field(
        description="Command ID; echoed as cmd_id in ack and run.",
        json_schema_extra=meta(since=2),
    )


_CMD_TS_DESC = "Send time on the laptop, Unix seconds UTC."


class CmdStart(_Cmd):
    """Start a run."""

    action: Literal["start"] = Field(
        alias="act", description="Action to perform.", json_schema_extra=meta(since=2)
    )
    duration: Annotated[int, Field(gt=0)] | None = Field(
        alias="dur",
        description="Planned duration of the run; null = the device's configured "
        "default duration.",
        json_schema_extra=meta(unit="s", since=2),
    )
    session: Uuid | None = Field(
        description="Session the run belongs to; null if none.",
        json_schema_extra=meta(since=2),
    )
    profile: ProfileName | None = Field(
        description="Profile to measure with; null = the device's default profile. A "
        "name the device does not have is answered with ack rejected.",
        json_schema_extra=meta(since=2),
    )
    run: None = Field(
        description="Always null for start: the device assigns the run ID.",
        json_schema_extra=meta(since=2),
    )
    timestamp: LaptopTimestamp = Field(
        alias="ts", description=_CMD_TS_DESC, json_schema_extra=meta(unit="s", since=2)
    )


class CmdStop(_Cmd):
    """Stop a run. The device ignores it (ack rejected) unless run is its active run."""

    action: Literal["stop"] = Field(
        alias="act", description="Action to perform.", json_schema_extra=meta(since=2)
    )
    duration: None = Field(
        alias="dur",
        description="Always null for stop.",
        json_schema_extra=meta(since=2),
    )
    session: None = Field(
        description="Always null for stop.", json_schema_extra=meta(since=2)
    )
    profile: None = Field(
        description="Always null for stop.", json_schema_extra=meta(since=2)
    )
    run: Count = Field(
        description="Run to stop.",
        json_schema_extra=meta(since=2),
    )
    timestamp: LaptopTimestamp = Field(
        alias="ts", description=_CMD_TS_DESC, json_schema_extra=meta(unit="s", since=2)
    )


CmdMessage = Annotated[CmdStart | CmdStop, Field(discriminator="action")]


class SessionMessage(MessageHeader):
    """Creates a session: runs started together for one experiment."""

    kind: Literal["session"] = Field(alias="k", json_schema_extra=meta(since=2))
    id: Uuid = Field(
        description="Session ID, generated by the CLI; referenced as session in cmd and "
        "run.",
        json_schema_extra=meta(since=2),
    )
    title: str = Field(description="Short title.", json_schema_extra=meta(since=2))
    variety: SessionVariety = Field(
        description="Kind of session; applies to all of its runs.",
        json_schema_extra=meta(since=2),
    )
    timestamp: LaptopTimestamp = Field(
        alias="ts",
        description="Creation time on the laptop, Unix seconds UTC.",
        json_schema_extra=meta(unit="s", since=2),
    )


class AnnotationMessage(MessageHeader):
    """Time-stamped note, optionally tied to a device, a run or a session."""

    model_config = ConfigDict(
        # Both keys are always present, so dependentRequired cannot express this.
        json_schema_extra={
            "if": {"properties": {"dev": {"type": "null"}}},
            "then": {"properties": {"run": {"type": "null"}}},
        },
    )

    kind: Literal["annotation"] = Field(alias="k", json_schema_extra=meta(since=2))
    id: Uuid = Field(
        description="Annotation ID, generated by the CLI; lets the pipeline drop "
        "duplicates from QoS 1.",
        json_schema_extra=meta(since=2),
    )
    timestamp: LaptopTimestamp = Field(
        alias="ts",
        description="Time the note refers to, Unix seconds UTC.",
        json_schema_extra=meta(unit="s", since=2),
    )
    text: str = Field(description="Note text.", json_schema_extra=meta(since=2))
    device_id: HexId16 | None = Field(
        alias="dev",
        description="Device the note refers to; null if none.",
        json_schema_extra=meta(since=2),
    )
    run: Count | None = Field(
        description="Run of dev the note refers to; requires dev. null if none.",
        json_schema_extra=meta(since=2),
    )
    session: Uuid | None = Field(
        description="Session the note refers to; null if none.",
        json_schema_extra=meta(since=2),
    )

    @model_validator(mode="after")
    def _run_requires_dev(self) -> Self:
        if self.run is not None and self.device_id is None:
            raise ValueError("run requires dev")
        return self


class TagMessage(MessageHeader):
    """
    Sets or deletes a key/value tag on a run. Every message is kept as history; the
    current value of a key is the one with the newest ts.
    """

    kind: Literal["tag"] = Field(alias="k", json_schema_extra=meta(since=2))
    id: Uuid = Field(
        description="Tag message ID, generated by the CLI; lets the pipeline drop "
        "duplicates from QoS 1.",
        json_schema_extra=meta(since=2),
    )
    device_id: HexId16 = Field(
        alias="dev",
        description="Device of the run.",
        json_schema_extra=meta(since=2),
    )
    run: Count = Field(
        description="Run of dev the tag belongs to. May arrive before the run's start "
        "record.",
        json_schema_extra=meta(since=2),
    )
    key: TagKey = Field(
        description="Tag name: lower case letters, digits and _.",
        json_schema_extra=meta(since=2),
    )
    value: str | None = Field(
        description="Tag value; null deletes the tag.",
        json_schema_extra=meta(since=2),
    )
    timestamp: LaptopTimestamp = Field(
        alias="ts",
        description="Time on the laptop, Unix seconds UTC; the newest ts per key is the "
        "current value.",
        json_schema_extra=meta(unit="s", since=2),
    )


LaptopMessage = Annotated[
    CmdMessage | SessionMessage | AnnotationMessage | TagMessage,
    Field(discriminator="kind"),
]

LAPTOP_MODELS = (CmdStart, CmdStop, SessionMessage, AnnotationMessage, TagMessage)
LAPTOP_KINDS: dict[str, Any] = {
    "cmd": CmdMessage,
    "session": SessionMessage,
    "annotation": AnnotationMessage,
    "tag": TagMessage,
}
"""Schema target per k; a kind with variants maps to its discriminated union."""

laptop_adapter: TypeAdapter[LaptopMessage] = TypeAdapter(LaptopMessage)


def parse_laptop_message(
    line: str | bytes, *, forbid_extra: bool = False
) -> LaptopMessage:
    """Validate one JSON message from the laptop (cmd, session, annotation, tag)."""
    return laptop_adapter.validate_json(line, context={FORBID_EXTRA: forbid_extra})


def validate_laptop_message(obj: Any, *, forbid_extra: bool = False) -> LaptopMessage:
    return laptop_adapter.validate_python(obj, context={FORBID_EXTRA: forbid_extra})
